#[cfg(test)]
mod tests {
    use super::{Book, LONG_BANDS, SCALEFACTOR, SHORT_BANDS, SPECTRUM, TNS_LONG_BANDS};
    use crate::bits::Reader;

    /// Every book must use up exactly its code space (Kraft), or the transcription is wrong.
    fn kraft(book: &Book) -> f64 {
        book.lengths
            .iter()
            .enumerate()
            .map(|(at, &(count, _, _))| f64::from(count) / (2f64).powi(at as i32 + 1))
            .sum()
    }

    #[test]
    fn every_book_fills_its_code_space() {
        for book in SPECTRUM {
            assert!((kraft(book) - 1.0).abs() < 1e-9);
        }
        assert!((kraft(&SCALEFACTOR) - 1.0).abs() < 1e-9);
    }

    #[test]
    fn a_codeword_reads_back_as_the_index_it_stands_for() {
        let mut reader = Reader::new(&[0b0000_0000]);
        assert_eq!(SPECTRUM[0].read(&mut reader), 40);
        let mut reader = Reader::new(&[0b0000_0000]);
        assert_eq!(SCALEFACTOR.read(&mut reader), 60);
    }

    #[test]
    fn the_band_tables_are_shaped_the_way_the_decoder_assumes() {
        for (at, bands) in LONG_BANDS.iter().enumerate() {
            assert_eq!(bands[0], 0);
            assert_eq!(*bands.last().expect("bands"), 1024);
            assert!(bands.windows(2).all(|pair| pair[0] < pair[1]));
            assert!(usize::from(TNS_LONG_BANDS[at]) < bands.len());
        }
        for bands in SHORT_BANDS {
            assert_eq!(bands[0], 0);
            assert_eq!(*bands.last().expect("bands"), 128);
        }
    }
}
