//! The tables of ISO/IEC 14496-3. Huffman books are stored as canonical codes (checked by a test).

use crate::bits::Reader;

#[derive(Debug)]
pub struct Book {
    /// Per code length from one: count, first codeword, and where its values begin.
    pub lengths: &'static [(u16, u32, u16)],
    /// The index each codeword stands for, in codeword order.
    pub values: &'static [u16],
}

impl Book {
    /// Reads one codeword. A damaged one gives the first index rather than failing.
    pub fn read(&self, reader: &mut Reader<'_>) -> u16 {
        let mut code = 0u32;
        for &(count, first, base) in self.lengths {
            code = code << 1 | reader.bit();
            if count > 0 && code >= first && code - first < u32::from(count) {
                let at = usize::from(base) + (code - first) as usize;
                return self.values[at];
            }
        }
        0
    }
}

