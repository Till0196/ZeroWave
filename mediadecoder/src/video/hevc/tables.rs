/// Table 8-10: chroma QP at 4:2:0; only the middle range differs, so only it is tabulated.
pub fn chroma_qp(qpi: i32) -> i32 {
    const MIDDLE: [i32; 14] = [29, 30, 31, 32, 33, 33, 34, 34, 35, 35, 36, 36, 37, 37];
    if qpi < 30 {
        qpi
    } else if qpi > 43 {
        qpi - 6
    } else {
        MIDDLE[(qpi - 30) as usize]
    }
}

