//! Constant tables of Rec. ITU-T H.265, copied as the standard prints them.
//! Tables that are rules (scans, scaling factors) are `const fn`s evaluated at compile time.

/// `SIDE` and `COUNT` are both given because `SIDE * SIDE` cannot yet be written in a type.
const fn scan<const SIDE: usize, const COUNT: usize>(mode: usize) -> [[u8; 2]; COUNT] {
    let mut out = [[0u8; 2]; COUNT];
    match mode {
        // 6.5.3, equation 6-11: each anti-diagonal from its bottom left end, up and to the right.
        0 => {
            let mut i = 0usize;
            let mut x: isize = 0;
            let mut y: isize = 0;
            loop {
                while y >= 0 {
                    if x < SIDE as isize && y < SIDE as isize {
                        out[i] = [x as u8, y as u8];
                        i += 1;
                    }
                    y -= 1;
                    x += 1;
                }
                y = x;
                x = 0;
                if i >= COUNT {
                    break;
                }
            }
        }
        // 6.5.4: row by row.
        1 => {
            let mut i = 0usize;
            let mut y = 0;
            while y < SIDE {
                let mut x = 0;
                while x < SIDE {
                    out[i] = [x as u8, y as u8];
                    i += 1;
                    x += 1;
                }
                y += 1;
            }
        }
        // 6.5.5: column by column.
        _ => {
            let mut i = 0usize;
            let mut x = 0;
            while x < SIDE {
                let mut y = 0;
                while y < SIDE {
                    out[i] = [x as u8, y as u8];
                    i += 1;
                    y += 1;
                }
                x += 1;
            }
        }
    }
    out
}

pub const SCAN_4: [[[u8; 2]; 16]; 3] = [scan::<4, 16>(0), scan::<4, 16>(1), scan::<4, 16>(2)];
pub const SCAN_2: [[[u8; 2]; 4]; 3] = [scan::<2, 4>(0), scan::<2, 4>(1), scan::<2, 4>(2)];
/// The 4x4 grid of sub-blocks of 16x16; all three written so `scanIdx` needs no special case.
pub const SCAN_4G: [[[u8; 2]; 16]; 3] = SCAN_4;
pub const SCAN_8: [[[u8; 2]; 64]; 3] = [scan::<8, 64>(0), scan::<8, 64>(1), scan::<8, 64>(2)];

pub fn scan_order(log2: usize, mode: usize) -> &'static [[u8; 2]] {
    match log2 {
        0 => &[[0, 0]],
        1 => &SCAN_2[mode],
        2 => &SCAN_4G[mode],
        _ => &SCAN_8[mode],
    }
}

